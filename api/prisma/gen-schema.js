// Generates prisma/schema.prisma from prisma/spec.js:  npm run prisma:schema
const fs = require('fs');
const path = require('path');
const { spec, model, delegate, columns, order } = require('../src/db/mapping');

const PRISMA = { s: 'String', i: 'Int', b: 'Boolean', d: 'DateTime @db.Timestamptz(3)', D: 'DateTime @db.Date', e: 'DateTime @db.Timestamptz(3)', j: 'Json', ss: 'String[]' };
const rel = (c, f) => (/Id$/.test(f) ? f.replace(/Id$/, '') : f + 'Ref');
const relName = (c, f) => `${c}_${f}`;

const back = {}; // parent collection -> [lines]
for (const c of Object.keys(spec)) for (const [f, [parent]] of Object.entries(spec[c].fk || {})) {
  const nullable = spec[c].fk[f][1];
  (back[parent] ||= []).push(`  ${c}_${f} ${model(c)}[] @relation("${relName(c, f)}")${nullable ? '' : ''}`);
}

let out = `// GENERATED by prisma/gen-schema.js from prisma/spec.js — run \`npm run prisma:schema\`; don't edit by hand.
generator client {
  provider = "prisma-client-js"
}

datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}
`;
for (const c of order()) {
  const s = spec[c];
  const lines = ['  id        String   @id', '  createdAt DateTime @default(now()) @db.Timestamptz(3)'];
  const cols = columns(c);
  for (const col of cols) {
    let t = PRISMA[col.type];
    if (col.nullable && col.type !== 'ss') t = t.replace(/^(\w+)/, '$1?');
    const [base, ...rest] = t.split(' ');
    lines.push(`  ${col.name.padEnd(9)} ${base.padEnd(8)}${rest.length ? ' ' + rest.join(' ') : ''}`.trimEnd());
  }
  lines.push('  extra     Json?');
  for (const [f, [parent, nullable]] of Object.entries(s.fk || {})) {
    const rf = rel(c, f);
    if (cols.some((x) => x.name === rf) || ['id', 'createdAt', 'extra'].includes(rf)) throw new Error(`relation name clash ${c}.${rf}`);
    lines.push(`  ${rf} ${model(parent)}${nullable ? '?' : ''} @relation("${relName(c, f)}", fields: [${f}], references: [id], onDelete: ${nullable ? 'SetNull' : 'Cascade'})`);
  }
  for (const l of back[c] || []) lines.push(l);
  lines.push('');
  for (const u of s.unique || []) lines.push(`  @@unique([${u}])`);
  for (const i of s.index || []) lines.push(`  @@index([${i}])`);
  lines.push(`  @@map("${c}")`);
  out += `\nmodel ${model(c)} {\n${lines.join('\n')}\n}\n`;
}
fs.writeFileSync(path.join(__dirname, 'schema.prisma'), out);
console.log(`schema.prisma: ${Object.keys(spec).length} models`);
